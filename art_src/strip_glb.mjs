// Strip Quaternius UAL1 (CC0) to the clips the runner needs, prune, resample, quantize → base64 TS module.
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { prune, resample, quantize, dedup } from "@gltf-transform/functions";
import fs from "fs";

const KEEP = new Set(["Idle_Loop", "Jog_Fwd_Loop", "Sprint_Loop", "Jump_Start", "Jump_Loop", "Jump_Land", "Roll", "Death01", "Hit_Chest"]);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const doc = await io.read(process.argv[2]);
for (const a of doc.getRoot().listAnimations()) if (!KEEP.has(a.getName())) { a.listChannels().forEach((c) => c.dispose()); a.listSamplers().forEach((s) => { s.dispose(); }); a.dispose(); }
await doc.transform(resample({ tolerance: 1e-3 }), dedup(), prune(), quantize({ quantizePosition: 14, quantizeNormal: 10, quantizeTexcoord: 12 }));
const bin = await io.writeBinary(doc);
fs.writeFileSync("/tmp/gt/runner.glb", bin);
const b64 = Buffer.from(bin).toString("base64");
fs.writeFileSync(process.argv[3], `// Generated by art_src/strip_glb.mjs from Quaternius "Universal Animation Library" (CC0 1.0). Do not edit.\n// Clips: ${[...KEEP].join(", ")}\nexport const RUNNER_GLB_BASE64 =\n  "${b64}";\n`);
console.log("glb bytes", bin.byteLength, "anims", doc.getRoot().listAnimations().map((a) => a.getName()).join(","));
